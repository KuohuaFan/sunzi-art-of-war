def clean_wiki(text: str) -> str:
    text = re.sub(r"\{\{另\|([^|{}]+)\|([^{}]+)\}\}", r"\1", text)
    text = re.sub(r"\[\[[^\]|]+\|([^\]]+)\]\]", r"\1", text)
    text = re.sub(r"\[\[([^\]]+)\]\]", r"\1", text)
    text = re.sub(r"\{\{[^{}]+\}\}", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def parse_chapters(source: str):
    chapter_re = re.compile(r"^==\s*(.+?)\s*==\s*$", re.M)
    matches = list(chapter_re.finditer(source))
    chapters = []
    for idx, match in enumerate(matches):
        heading = match.group(1)
        if heading == "答話":
            break
        body_end = matches[idx + 1].start() if idx + 1 < len(matches) else len(source)
        body = source[match.end():body_end].strip()
        paragraphs = [clean_wiki(p) for p in re.split(r"\n\s*\n", body) if clean_wiki(p)]
        chapters.append((heading, paragraphs))
    return chapters


